import { parseStrataLive, parseCompletedRequest, strataMetricsUrl, STRATA_POLL_INTERVAL_MS, STRATA_FETCH_TIMEOUT_MS, StrataMetricsPoller } from "../src/native-metrics.ts";
import { RunMetrics } from "../src/metrics.ts";
let failures=0;
function check(label:string,ok:boolean){if(ok)console.log("  ok  "+label);else{failures++;console.log(" FAIL "+label);}}
console.log("\n[strata-native metrics]");
const live=parseStrataLive({live:{state:"generating",tok_s:71.2,tok_s_mean:66,prefill_tok_s_mean:0,generated:142,elapsed_s:2}});
check("reads native live TPS",live?.liveTps===71.2);
check("reads native turn mean",live?.meanTps===66);
check("reads PP TPS",parseStrataLive({live:{state:"reading",prefill_tok_s_mean:1200}})?.ppTps===1200);
check("ignores idle state",parseStrataLive({live:{state:"idle"}})===null);
const prior={time:100,output_tokens:10,decode_tok_s:10,decode_ms:1000};
const fresh={time:101,output_tokens:300,decode_tok_s:30,decode_ms:10000};
check("stale request excluded by baseline",parseCompletedRequest({requests:[prior]},100)===null);
const completed=parseCompletedRequest({requests:[fresh,prior]},100);
check("fresh completed output parsed",completed?.outputTokens===300);
check("decode_ms is used, not duration_s",completed?.decodeSeconds===10);
check("missing decode_ms is unavailable",parseCompletedRequest({requests:[{...fresh,decode_ms:null,duration_s:90}]},100)===null);
check("non-Strata provider disabled",strataMetricsUrl("openai",[])===null);
check("provider URL maps /v1 to local metrics",strataMetricsUrl("strata-auto",[{provider:"strata-auto",config:{baseUrl:"http://127.0.0.1:8080/v1"}}])==="http://127.0.0.1:8080/metrics");
check("poll interval follows reference",STRATA_POLL_INTERVAL_MS===300&&STRATA_FETCH_TIMEOUT_MS===500);
console.log("[native reconcile + fallback]");
let now=1000;const metrics=new RunMetrics(()=>now,4);metrics.start();
metrics.beginAssistantMessage();now=1100;metrics.contentStarted();metrics.outputDelta("x".repeat(400));now=2100;metrics.endAssistantMessage({output:100},"toolUse");
check("native final replaces estimate and usage",metrics.reconcileLastWithNative(300,2));
metrics.beginAssistantMessage();now=2200;metrics.contentStarted();metrics.outputDelta("y".repeat(400));now=3200;metrics.endAssistantMessage({output:100},"stop");
check("fallback request remains present after tool/multiple turns",metrics.snapshot().generations===2);
check("task weighted TPS uses sum tokens / sum decode seconds",Math.abs(metrics.snapshot().weightedTps-(metrics.snapshot().outputTokens/(metrics.snapshot().genMs/1000)))<1e-6);
const originalFetch=globalThis.fetch;globalThis.fetch=async()=>{throw new Error("offline")};
const unavailable=new StrataMetricsPoller("http://127.0.0.1:1/metrics",300,10);
await unavailable.start();
check("missing /metrics returns null fallback",await unavailable.finalizeRequest()===null);
unavailable.stop();globalThis.fetch=originalFetch;
if(failures)process.exit(1);console.log("NATIVE TESTS PASSED");
